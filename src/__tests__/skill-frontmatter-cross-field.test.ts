/**
 * skill-frontmatter cross-field invariant (kyh9 — CTO re-scope).
 *
 * The originally-specified cross-field invariant was infeasible (it would have
 * broken the D8 ajv↔Zod fold-agreement). Per the CTO ruling it was RE-SCOPED to
 * the DOCUMENTED invariant carried in the is-overlay `$comment`:
 *
 *   requires_env and fallback_for_env are mutually exclusive PER VARIABLE —
 *   a single identifier must not appear in BOTH arrays (a variable cannot be
 *   declared required-present AND simultaneously carry a fallback).
 *
 * This is an array-element-disjointness predicate. Vanilla JSON Schema 2020-12
 * cannot express it (there is no cross-array intersection keyword; ajv can only
 * do it with the non-standard `$data` extension, which would silently no-op for
 * any standard validator and break the language-agnostic wire contract). So per
 * the CTO ruling it lands as a DOCUMENTED CARVE-OUT: the predicate is enforced
 * in the Zod runtime layer (generated by codegen-authoring.ts from the overlay
 * schema's `x-mutually-exclusive-fields` annotation) and is intentionally NOT
 * mirrored in the published JSON Schema.
 *
 * This test pins all three facets:
 *   1. the Zod composition REJECTS overlaps and ACCEPTS disjoint declarations
 *      (the invariant is real);
 *   2. the published JSON Schema (ajv) ACCEPTS the overlap (the carve-out is
 *      genuine and bounded — ajv cannot express it);
 *   3. on the disjoint fixtures ajv and Zod still AGREE (the carve-out is the
 *      ONLY place the two diverge — the D8 backstop otherwise holds).
 */

import { describe, it, expect, beforeAll } from 'vitest';
import Ajv2020Module from 'ajv/dist/2020.js';
import addFormatsModule from 'ajv-formats';
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SkillFrontmatterSchema } from '../validators/v1/authoring/skill-frontmatter.js';

interface ValidateFn {
  (data: unknown): boolean;
  errors: { instancePath: string; message?: string }[] | null;
}
interface AjvInstance {
  addSchema(schema: Record<string, unknown>, key?: string): void;
  getSchema(ref: string): ValidateFn | undefined;
  addKeyword(def: { keyword: string }): AjvInstance;
}

const Ajv2020 = (Ajv2020Module as unknown as { default: new (opts: object) => AjvInstance })
  .default;
const addFormats = (addFormatsModule as unknown as { default: (ajv: AjvInstance) => void }).default;

const __dirname = dirname(fileURLToPath(import.meta.url));
const AUTHORING_DIR = join(__dirname, '../../schemas/authoring/v1');
const CF_DIR = join(__dirname, '../../tests/authoring/v1/cross-field/skill-frontmatter');
const BASE = 'https://github.com/jeremylongshore/intent-eval-core/schemas/authoring/v1';
const COMPOSITION_ID = `${BASE}/skill-frontmatter.schema.json`;

function loadJson(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(path, 'utf-8')) as Record<string, unknown>;
}
function listJson(prefix: string): string[] {
  return readdirSync(CF_DIR)
    .filter((f) => f.endsWith('.json') && f.startsWith(prefix))
    .sort();
}
function fixture(file: string): unknown {
  return JSON.parse(readFileSync(join(CF_DIR, file), 'utf-8'));
}
function zodAccepts(obj: unknown): boolean {
  return SkillFrontmatterSchema.safeParse(obj).success;
}

let validateComposition: ValidateFn;

beforeAll(() => {
  const ajv = new Ajv2020({ strict: true, strictRequired: false, allErrors: true });
  addFormats(ajv);
  // x-mutually-exclusive-fields is a codegen-only vendor annotation (kyh9); ajv
  // never enforces it (the predicate is not JSON-Schema-expressible). Register it
  // as a benign no-op so strict mode tolerates it on the published overlay.
  ajv.addKeyword({ keyword: 'x-mutually-exclusive-fields' });
  ajv.addSchema(loadJson(join(AUTHORING_DIR, 'marketplace-tier.schema.json')));
  ajv.addSchema(loadJson(join(AUTHORING_DIR, 'upstream-base/skill-frontmatter.v1.json')));
  ajv.addSchema(loadJson(join(AUTHORING_DIR, 'is-overlay/skill-frontmatter.v1.json')));
  ajv.addSchema(loadJson(join(AUTHORING_DIR, 'skill-frontmatter.schema.json')));
  validateComposition = ajv.getSchema(COMPOSITION_ID)!;
});

describe('skill-frontmatter cross-field invariant — Zod enforcement (kyh9)', () => {
  it('rejects every overlap fixture (an identifier in both requires_env and fallback_for_env)', () => {
    const overlaps = listJson('violation-');
    expect(overlaps.length).toBeGreaterThan(0);
    for (const file of overlaps) {
      expect(zodAccepts(fixture(file)), `${file} must be rejected by Zod`).toBe(false);
    }
  });

  it('accepts every disjoint fixture (the invariant holds)', () => {
    const valids = listJson('valid-');
    expect(valids.length).toBeGreaterThan(0);
    for (const file of valids) {
      expect(zodAccepts(fixture(file)), `${file} must be accepted by Zod`).toBe(true);
    }
  });

  it('names both offending fields in the rejection message', () => {
    const result = SkillFrontmatterSchema.safeParse(
      fixture('violation-01-overlap-single-var.json'),
    );
    expect(result.success).toBe(false);
    if (!result.success) {
      const messages = result.error.issues.map((i) => i.message);
      expect(
        messages.some((m) => m.includes('requires_env') && m.includes('fallback_for_env')),
      ).toBe(true);
    }
  });
});

describe('skill-frontmatter cross-field invariant — DOCUMENTED ajv carve-out (kyh9)', () => {
  it('the overlay declares the invariant as x-mutually-exclusive-fields (not as JSON-Schema structure)', () => {
    const overlay = loadJson(join(AUTHORING_DIR, 'is-overlay/skill-frontmatter.v1.json'));
    const groups = overlay['x-mutually-exclusive-fields'] as { fields: string[] }[] | undefined;
    expect(groups).toBeDefined();
    expect(groups?.[0]?.fields).toEqual(['requires_env', 'fallback_for_env']);
  });

  it('ajv (pure JSON Schema) ACCEPTS the overlap — proving the carve-out is real, not an oversight', () => {
    // The invariant is not expressible in vanilla JSON Schema, so ajv must accept
    // the overlap. This is the bounded, intentional divergence from the Zod layer.
    for (const file of listJson('violation-')) {
      expect(validateComposition(fixture(file)), `ajv must accept ${file} (cannot express)`).toBe(
        true,
      );
    }
  });

  it('on disjoint fixtures ajv and Zod AGREE (the carve-out is the ONLY divergence)', () => {
    for (const file of listJson('valid-')) {
      const obj = fixture(file);
      expect(validateComposition(obj)).toBe(true);
      expect(zodAccepts(obj)).toBe(true);
    }
  });
});
